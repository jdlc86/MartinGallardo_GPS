create or replace function public.parking_booking_require_admin(p_actor_telegram_user_id bigint)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if not exists (
    select 1
    from public.telegram_users
    where telegram_user_id = p_actor_telegram_user_id
      and active = true
      and role in ('owner', 'admin')
  ) then
    raise exception using errcode = '42501', message = 'not_admin';
  end if;
end;
$$;

create or replace function public.parking_booking_require_writer(p_actor_telegram_user_id bigint, p_writer_epoch bigint)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_state public.parking_booking_write_state%rowtype;
begin
  perform public.parking_booking_require_admin(p_actor_telegram_user_id);
  select * into v_state
  from public.parking_booking_write_state
  where id = 1
  for update;
  if v_state.holder_telegram_user_id is distinct from p_actor_telegram_user_id then
    raise exception using errcode = '42501', message = 'write_permission_required';
  end if;
  if v_state.epoch is distinct from p_writer_epoch then
    raise exception using errcode = '40001', message = 'write_permission_changed';
  end if;
end;
$$;

create or replace function public.parking_booking_normalize_entry(p_entry jsonb)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_pickup_date date;
  v_pickup_time time without time zone;
  v_return_date date;
  v_return_time time without time zone;
  v_pickup_terminal text;
  v_return_terminal text;
  v_customer_name text;
  v_customer_email text;
  v_customer_phone text;
  v_vehicle_plate text;
  v_vehicle_make_model text;
  v_payment text;
  v_price_text text;
  v_price numeric(10,2);
begin
  if p_entry is null or jsonb_typeof(p_entry) <> 'object' then
    raise exception using errcode = '22023', message = 'invalid_booking_entry';
  end if;

  v_pickup_date := nullif(trim(p_entry ->> 'pickup_date'), '')::date;
  v_pickup_time := nullif(trim(p_entry ->> 'pickup_time'), '')::time;
  v_return_date := nullif(trim(p_entry ->> 'return_date'), '')::date;
  v_return_time := nullif(trim(p_entry ->> 'return_time'), '')::time;
  v_pickup_terminal := nullif(trim(p_entry ->> 'pickup_terminal'), '');
  v_return_terminal := nullif(trim(p_entry ->> 'return_terminal'), '');
  v_customer_name := nullif(trim(p_entry ->> 'customer_name'), '');
  v_customer_email := nullif(lower(trim(p_entry ->> 'customer_email')), '');
  v_customer_phone := nullif(trim(p_entry ->> 'customer_phone'), '');
  v_vehicle_plate := nullif(upper(trim(p_entry ->> 'vehicle_plate')), '');
  v_vehicle_make_model := nullif(trim(p_entry ->> 'vehicle_make_model'), '');
  v_payment := lower(trim(coalesce(p_entry ->> 'payment_method', '')));
  v_price_text := regexp_replace(coalesce(p_entry ->> 'price_eur', ''), '[€[:space:]]', '', 'g');
  if position(',' in v_price_text) > 0 and position('.' in v_price_text) > 0 then
    v_price_text := replace(replace(v_price_text, '.', ''), ',', '.');
  else
    v_price_text := replace(v_price_text, ',', '.');
  end if;
  v_price := nullif(v_price_text, '')::numeric(10,2);

  if v_payment in ('efectivo', 'cash') then v_payment := 'cash'; end if;
  if v_payment in ('tarjeta', 'tarjeta de credito', 'tarjeta de crédito', 'credito', 'crédito', 'card', 'credit_card') then v_payment := 'credit_card'; end if;

  if v_pickup_date is null or v_pickup_time is null or v_return_date is null or v_return_time is null
     or v_pickup_terminal is null or v_return_terminal is null or v_customer_name is null
     or v_vehicle_plate is null or v_price is null or v_payment not in ('cash', 'credit_card') then
    raise exception using errcode = '22023', message = 'invalid_booking_entry';
  end if;
  if v_return_date < v_pickup_date then
    raise exception using errcode = '22023', message = 'invalid_booking_dates';
  end if;
  if v_price < 0 then
    raise exception using errcode = '22023', message = 'invalid_booking_price';
  end if;
  if char_length(v_pickup_terminal) > 120 or char_length(v_return_terminal) > 120
     or char_length(v_customer_name) > 180 or char_length(v_vehicle_plate) > 24
     or char_length(coalesce(v_vehicle_make_model, '')) > 180
     or char_length(coalesce(v_customer_phone, '')) > 80
     or char_length(coalesce(v_customer_email, '')) > 254 then
    raise exception using errcode = '22023', message = 'booking_value_too_long';
  end if;
  if v_customer_email is not null and v_customer_email !~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception using errcode = '22023', message = 'invalid_booking_email';
  end if;

  return jsonb_build_object(
    'pickup_date', to_char(v_pickup_date, 'YYYY-MM-DD'),
    'pickup_time', to_char(v_pickup_time, 'HH24:MI'),
    'pickup_terminal', v_pickup_terminal,
    'return_date', to_char(v_return_date, 'YYYY-MM-DD'),
    'return_time', to_char(v_return_time, 'HH24:MI'),
    'return_terminal', v_return_terminal,
    'price_eur', v_price,
    'customer_name', v_customer_name,
    'customer_email', v_customer_email,
    'customer_phone', v_customer_phone,
    'vehicle_plate', v_vehicle_plate,
    'vehicle_make_model', v_vehicle_make_model,
    'payment_method', v_payment,
    'source_row', case when coalesce(p_entry ->> 'source_row', '') ~ '^[0-9]+$' then (p_entry ->> 'source_row')::integer else null end
  );
exception
  when invalid_text_representation or datetime_field_overflow or numeric_value_out_of_range then
    raise exception using errcode = '22023', message = 'invalid_booking_entry';
end;
$$;

create or replace function public.parking_booking_dashboard(
  p_actor_telegram_user_id bigint,
  p_query text,
  p_limit integer,
  p_offset integer
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_query text := trim(coalesce(p_query, ''));
  v_limit integer := least(greatest(coalesce(p_limit, 50), 1), 200);
  v_offset integer := greatest(coalesce(p_offset, 0), 0);
  v_result jsonb;
begin
  perform public.parking_booking_require_admin(p_actor_telegram_user_id);

  select jsonb_build_object(
    'me', (
      select jsonb_build_object(
        'telegram_user_id', u.telegram_user_id,
        'role', u.role,
        'name', coalesce(nullif(trim(concat_ws(' ', u.first_name, u.last_name)), ''), case when u.username is not null then '@' || u.username else 'Usuario ' || u.telegram_user_id::text end)
      )
      from public.telegram_users u
      where u.telegram_user_id = p_actor_telegram_user_id
    ),
    'permission', (
      select jsonb_build_object(
        'holder_telegram_user_id', s.holder_telegram_user_id,
        'holder_name', coalesce(nullif(trim(concat_ws(' ', h.first_name, h.last_name)), ''), case when h.username is not null then '@' || h.username else 'Sin titular' end),
        'epoch', s.epoch,
        'can_write', s.holder_telegram_user_id = p_actor_telegram_user_id,
        'granted_at', s.granted_at
      )
      from public.parking_booking_write_state s
      left join public.telegram_users h on h.telegram_user_id = s.holder_telegram_user_id
      where s.id = 1
    ),
    'admins', (
      select coalesce(jsonb_agg(to_jsonb(a) order by a.is_root desc, a.name), '[]'::jsonb)
      from (
        select u.telegram_user_id,
               u.role,
               (u.role = 'owner') as is_root,
               coalesce(nullif(trim(concat_ws(' ', u.first_name, u.last_name)), ''), case when u.username is not null then '@' || u.username else 'Usuario ' || u.telegram_user_id::text end) as name
        from public.telegram_users u
        where u.active = true and u.role in ('owner', 'admin')
      ) a
    ),
    'reservations', (
      select coalesce(jsonb_agg(to_jsonb(r) order by r.pickup_date, r.pickup_time, r.created_at), '[]'::jsonb)
      from (
        select b.id, b.pickup_date, b.pickup_time, b.pickup_terminal,
               b.return_date, b.return_time, b.return_terminal, b.price_eur,
               b.customer_name, b.customer_email, b.customer_phone,
               b.vehicle_plate, b.vehicle_plate_normalized, b.vehicle_make_model,
               b.payment_method, b.source_type, b.source_row, b.version,
               b.created_at, b.updated_at
        from public.parking_bookings b
        where b.deleted_at is null
          and (
            v_query = ''
            or b.customer_name ilike '%' || v_query || '%'
            or coalesce(b.customer_email, '') ilike '%' || v_query || '%'
            or coalesce(b.customer_phone, '') ilike '%' || v_query || '%'
            or b.vehicle_plate ilike '%' || v_query || '%'
            or b.vehicle_plate_normalized ilike '%' || upper(regexp_replace(v_query, '[^[:alnum:]]', '', 'g')) || '%'
            or coalesce(b.vehicle_make_model, '') ilike '%' || v_query || '%'
            or b.pickup_terminal ilike '%' || v_query || '%'
            or b.return_terminal ilike '%' || v_query || '%'
            or to_char(b.pickup_date, 'DD/MM/YYYY') ilike '%' || v_query || '%'
            or to_char(b.return_date, 'DD/MM/YYYY') ilike '%' || v_query || '%'
          )
        order by b.pickup_date, b.pickup_time, b.created_at
        limit v_limit offset v_offset
      ) r
    ),
    'total', (
      select count(*)
      from public.parking_bookings b
      where b.deleted_at is null
        and (
          v_query = ''
          or b.customer_name ilike '%' || v_query || '%'
          or coalesce(b.customer_email, '') ilike '%' || v_query || '%'
          or coalesce(b.customer_phone, '') ilike '%' || v_query || '%'
          or b.vehicle_plate ilike '%' || v_query || '%'
          or b.vehicle_plate_normalized ilike '%' || upper(regexp_replace(v_query, '[^[:alnum:]]', '', 'g')) || '%'
          or coalesce(b.vehicle_make_model, '') ilike '%' || v_query || '%'
          or b.pickup_terminal ilike '%' || v_query || '%'
          or b.return_terminal ilike '%' || v_query || '%'
          or to_char(b.pickup_date, 'DD/MM/YYYY') ilike '%' || v_query || '%'
          or to_char(b.return_date, 'DD/MM/YYYY') ilike '%' || v_query || '%'
        )
    ),
    'stats', (
      select jsonb_build_object(
        'active', count(*) filter (where deleted_at is null),
        'today', count(*) filter (where deleted_at is null and pickup_date = current_date),
        'upcoming', count(*) filter (where deleted_at is null and pickup_date > current_date),
        'imported', count(*) filter (where deleted_at is null and source_type = 'ai_import')
      )
      from public.parking_bookings
    ),
    'notifications', (
      select coalesce(jsonb_agg(to_jsonb(n) order by n.created_at desc), '[]'::jsonb)
      from (
        select id, notification_type, title, body, permission_request_id, payload, read_at, created_at
        from public.parking_booking_notifications
        where recipient_telegram_user_id = p_actor_telegram_user_id
        order by created_at desc
        limit 50
      ) n
    ),
    'unread_count', (
      select count(*) from public.parking_booking_notifications
      where recipient_telegram_user_id = p_actor_telegram_user_id and read_at is null
    ),
    'pending_requests', (
      select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at), '[]'::jsonb)
      from (
        select pr.id, pr.request_kind, pr.requester_telegram_user_id,
               pr.proposed_holder_telegram_user_id, pr.writer_epoch, pr.created_at, pr.expires_at,
               coalesce(nullif(trim(concat_ws(' ', rq.first_name, rq.last_name)), ''), case when rq.username is not null then '@' || rq.username else 'Usuario ' || rq.telegram_user_id::text end) as requester_name,
               coalesce(nullif(trim(concat_ws(' ', ph.first_name, ph.last_name)), ''), case when ph.username is not null then '@' || ph.username else 'Usuario ' || ph.telegram_user_id::text end) as proposed_holder_name
        from public.parking_booking_permission_requests pr
        join public.telegram_users rq on rq.telegram_user_id = pr.requester_telegram_user_id
        join public.telegram_users ph on ph.telegram_user_id = pr.proposed_holder_telegram_user_id
        where pr.recipient_telegram_user_id = p_actor_telegram_user_id
          and pr.status = 'pending'
          and pr.expires_at > now()
      ) x
    ),
    'outgoing_requests', (
      select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at), '[]'::jsonb)
      from (
        select pr.id, pr.request_kind, pr.recipient_telegram_user_id,
               pr.proposed_holder_telegram_user_id, pr.created_at, pr.expires_at,
               coalesce(nullif(trim(concat_ws(' ', rc.first_name, rc.last_name)), ''), case when rc.username is not null then '@' || rc.username else 'Usuario ' || rc.telegram_user_id::text end) as recipient_name
        from public.parking_booking_permission_requests pr
        join public.telegram_users rc on rc.telegram_user_id = pr.recipient_telegram_user_id
        where pr.requester_telegram_user_id = p_actor_telegram_user_id
          and pr.status = 'pending'
          and pr.expires_at > now()
      ) x
    )
  ) into v_result;

  return v_result;
end;
$$;

create or replace function public.parking_booking_create(
  p_actor_telegram_user_id bigint,
  p_writer_epoch bigint,
  p_idempotency_key uuid,
  p_entry jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_existing public.parking_booking_command_dedup%rowtype;
  v_norm jsonb;
  v_row public.parking_bookings%rowtype;
  v_response jsonb;
begin
  select * into v_existing from public.parking_booking_command_dedup where idempotency_key = p_idempotency_key;
  if found then
    if v_existing.actor_telegram_user_id <> p_actor_telegram_user_id or v_existing.action <> 'create' then
      raise exception using errcode = '22023', message = 'idempotency_key_reused';
    end if;
    return v_existing.response;
  end if;

  perform public.parking_booking_require_writer(p_actor_telegram_user_id, p_writer_epoch);
  v_norm := public.parking_booking_normalize_entry(p_entry);

