    values (v_request.requester_telegram_user_id, 'permission_expired', 'Solicitud caducada',
            'La solicitud ya no es válida porque el permiso de escritura cambió.', v_request.id);
    v_response := jsonb_build_object('status', 'expired', 'error', 'permission_request_stale');
    insert into public.parking_booking_command_dedup(idempotency_key, actor_telegram_user_id, action, response)
    values (p_idempotency_key, p_actor_telegram_user_id, 'respond_permission', v_response);
    return v_response;
  end if;

  if p_decision = 'reject' then
    update public.parking_booking_permission_requests
    set status = 'rejected', responded_by_telegram_user_id = p_actor_telegram_user_id, responded_at = now()
    where id = v_request.id;
    insert into public.parking_booking_notifications(recipient_telegram_user_id, notification_type, title, body, permission_request_id)
    values (v_request.requester_telegram_user_id, 'permission_rejected', 'Solicitud rechazada',
            'La solicitud de Lectura/Escritura ha sido rechazada.', v_request.id);
    insert into public.parking_booking_admin_events(actor_telegram_user_id, action, entity_type, entity_id, permission_request_id, before_data, after_data)
    values (p_actor_telegram_user_id, 'reject_permission', 'write_permission', v_request.proposed_holder_telegram_user_id::text,
            v_request.id, to_jsonb(v_state_before), to_jsonb(v_state_before));
    v_response := jsonb_build_object('status', 'rejected', 'permission', to_jsonb(v_state_before));
  else
    select exists (
      select 1 from public.telegram_users
      where telegram_user_id = v_request.proposed_holder_telegram_user_id
        and active = true and role in ('owner', 'admin')
    ) into v_target_active;
    if not v_target_active then raise exception using errcode = '22023', message = 'invalid_transfer_target'; end if;

    update public.parking_booking_write_state
    set holder_telegram_user_id = v_request.proposed_holder_telegram_user_id,
        epoch = epoch + 1,
        granted_by_telegram_user_id = p_actor_telegram_user_id,
        granted_at = now(),
        updated_at = now()
    where id = 1 returning * into v_state_after;
    update public.parking_booking_permission_requests
    set status = 'accepted', responded_by_telegram_user_id = p_actor_telegram_user_id, responded_at = now()
    where id = v_request.id;

    for v_expired in
      update public.parking_booking_permission_requests
      set status = 'expired', responded_at = now()
      where status = 'pending' and id <> v_request.id
      returning requester_telegram_user_id, id
    loop
      insert into public.parking_booking_notifications(recipient_telegram_user_id, notification_type, title, body, permission_request_id)
      values (v_expired.requester_telegram_user_id, 'permission_expired', 'Solicitud caducada',
              'La solicitud ha caducado porque cambió el titular de Lectura/Escritura.', v_expired.id);
    end loop;

    select coalesce(nullif(trim(concat_ws(' ', first_name, last_name)), ''), case when username is not null then '@' || username else 'Usuario ' || telegram_user_id::text end)
    into v_recipient_name from public.telegram_users where telegram_user_id = v_request.proposed_holder_telegram_user_id;
    insert into public.parking_booking_notifications(recipient_telegram_user_id, notification_type, title, body, permission_request_id)
    values (v_request.proposed_holder_telegram_user_id, 'permission_accepted', 'Permiso de Lectura/Escritura activo',
            'Ya puedes crear, modificar, importar y eliminar reservas.', v_request.id);
    if v_request.request_kind = 'transfer' then
      insert into public.parking_booking_notifications(recipient_telegram_user_id, notification_type, title, body, permission_request_id)
      values (v_request.requester_telegram_user_id, 'transfer_accepted', 'Transferencia aceptada',
              v_recipient_name || ' ha aceptado el permiso de Lectura/Escritura.', v_request.id);
    end if;
    insert into public.parking_booking_admin_events(actor_telegram_user_id, action, entity_type, entity_id, permission_request_id, before_data, after_data)
    values (p_actor_telegram_user_id, 'accept_permission', 'write_permission', v_request.proposed_holder_telegram_user_id::text,
            v_request.id, to_jsonb(v_state_before), to_jsonb(v_state_after));
    v_response := jsonb_build_object('status', 'accepted', 'permission', to_jsonb(v_state_after));
  end if;

  insert into public.parking_booking_command_dedup(idempotency_key, actor_telegram_user_id, action, response)
  values (p_idempotency_key, p_actor_telegram_user_id, 'respond_permission', v_response);
  return v_response;
end;
$$;

create or replace function public.parking_booking_mark_notifications_read(
  p_actor_telegram_user_id bigint,
  p_notification_ids jsonb
)
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_count integer;
begin
  perform public.parking_booking_require_admin(p_actor_telegram_user_id);
  if p_notification_ids is null or jsonb_typeof(p_notification_ids) <> 'array' then
    raise exception using errcode = '22023', message = 'invalid_notification_selection';
  end if;
  update public.parking_booking_notifications
  set read_at = coalesce(read_at, now())
  where recipient_telegram_user_id = p_actor_telegram_user_id
    and id in (select (value #>> '{}')::bigint from jsonb_array_elements(p_notification_ids));
  get diagnostics v_count = row_count;
  return v_count;
exception
  when invalid_text_representation then
    raise exception using errcode = '22023', message = 'invalid_notification_selection';
end;
$$;

create or replace function public.parking_booking_expire_permission_requests()
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_expired record;
  v_count integer := 0;
begin
  for v_expired in
    update public.parking_booking_permission_requests
    set status = 'expired', responded_at = now()
    where status = 'pending' and expires_at <= now()
    returning id, requester_telegram_user_id
  loop
    v_count := v_count + 1;
    insert into public.parking_booking_notifications(recipient_telegram_user_id, notification_type, title, body, permission_request_id)
    values (v_expired.requester_telegram_user_id, 'permission_expired', 'Solicitud caducada',
            'La solicitud de Lectura/Escritura ha caducado sin respuesta.', v_expired.id);
  end loop;
  return v_count;
end;
$$;

create or replace function public.parking_booking_claim_telegram_notifications(p_limit integer)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_result jsonb;
begin
  with candidates as (
    select id
    from public.parking_booking_notifications
    where telegram_sent_at is null
      and (telegram_claimed_at is null or telegram_claimed_at < now() - interval '5 minutes')
      and telegram_attempts < 8
    order by created_at
    for update skip locked
    limit least(greatest(coalesce(p_limit, 10), 1), 25)
  ), claimed as (
    update public.parking_booking_notifications n
    set telegram_claimed_at = now(), telegram_attempts = telegram_attempts + 1, telegram_error = null
    from candidates c
    where n.id = c.id
    returning n.id, n.recipient_telegram_user_id, n.title, n.body, n.notification_type, n.permission_request_id
  )
  select coalesce(jsonb_agg(to_jsonb(claimed)), '[]'::jsonb) into v_result from claimed;
  return v_result;
end;
$$;

create or replace function public.parking_booking_finish_telegram_notification(
  p_notification_id bigint,
  p_success boolean,
  p_error text
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
  update public.parking_booking_notifications
  set telegram_sent_at = case when p_success then now() else telegram_sent_at end,
      telegram_claimed_at = null,
      telegram_error = case when p_success then null else left(coalesce(p_error, 'telegram_error'), 500) end
  where id = p_notification_id;
end;
$$;

create or replace function public.parking_booking_repair_writer_after_admin_change()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_replacement bigint;
  v_state public.parking_booking_write_state%rowtype;
  v_expired record;
begin
  if new.active = true and new.role in ('owner', 'admin') then return new; end if;
  select * into v_state from public.parking_booking_write_state where id = 1 for update;
  if v_state.holder_telegram_user_id is distinct from new.telegram_user_id then return new; end if;

  select telegram_user_id into v_replacement
  from public.telegram_users
  where active = true and role = 'owner' and telegram_user_id <> new.telegram_user_id
  order by created_at limit 1;
  if v_replacement is null then
    select telegram_user_id into v_replacement
    from public.telegram_users
    where active = true and role = 'admin' and telegram_user_id <> new.telegram_user_id
    order by created_at limit 1;
  end if;

  update public.parking_booking_write_state
  set holder_telegram_user_id = v_replacement,
      epoch = epoch + 1,
      granted_by_telegram_user_id = null,
      granted_at = now(),
      updated_at = now()
  where id = 1;
  for v_expired in
    update public.parking_booking_permission_requests
    set status = 'expired', responded_at = now()
    where status = 'pending'
    returning id, requester_telegram_user_id
  loop
    insert into public.parking_booking_notifications(recipient_telegram_user_id, notification_type, title, body, permission_request_id)
    values (v_expired.requester_telegram_user_id, 'permission_expired', 'Solicitud caducada',
            'La solicitud ha caducado porque cambió el titular de Lectura/Escritura.', v_expired.id);
  end loop;
  insert into public.parking_booking_admin_events(actor_telegram_user_id, action, entity_type, entity_id, before_data, after_data, metadata)
  values (null, 'repair_writer', 'write_permission', coalesce(v_replacement::text, 'none'), to_jsonb(v_state),
          jsonb_build_object('holder_telegram_user_id', v_replacement, 'epoch', v_state.epoch + 1),
          jsonb_build_object('reason', 'holder_no_longer_active_admin'));
  if v_replacement is not null then
    insert into public.parking_booking_notifications(recipient_telegram_user_id, notification_type, title, body)
    values (v_replacement, 'permission_recovered', 'Permiso de escritura recuperado',
            'El sistema te ha asignado Lectura/Escritura porque el titular anterior dejó de ser administrador activo.');
  end if;
  return new;
end;
$$;

