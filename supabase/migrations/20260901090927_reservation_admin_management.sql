  v_state_after public.parking_booking_write_state%rowtype;
  v_target_active boolean;
  v_recipient_name text;
  v_status text;
  v_response jsonb;
  v_expired record;
begin
  select * into v_existing from public.parking_booking_command_dedup where idempotency_key = p_idempotency_key;
